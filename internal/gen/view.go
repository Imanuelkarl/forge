// FieldView is a field with every derived value the templates need precomputed,
// so the templates stay free of logic.
type FieldView struct {
	GoName   string
	Col      string
	Doc      string
	BaseType string // string, int, time.Time, ...
	GoType   string // entity field type (pointer when nullable)
	Nullable bool
	Unique   bool
	Required bool

	InCreate       bool
	InUpdate       bool
	CreateType     string
	CreateValidate string
	CreateAssign   string
	UpdateType     string
	UpdateValidate string
	UpdateAssign   string
	DefaultInit    string

	SampleCreate string // Go literal for the create DTO
	SampleUpdate string // Go literal for the update DTO (always a pointer)
	SampleJSON   string // JSON literal

	FindBySQL string // quoted Go string literal (unique fields only)
}

// CustomView is a custom endpoint.
type CustomView struct {
	Name        string
	GoMethod    string
	HTTPMethod  string
	MethodLower string
	Path        string
	Summary     string
	Permission  string
	HasID       bool
}

// SQLView holds pre-quoted Go string literals and argument lists for the SQL repository.
type SQLView struct {
	SelectByID string
	List       string
	Count      string
	Insert     string
	Update     string
	Delete     string
	ScanArgs   string
	InsertArgs string
	UpdateArgs string

	// InsertReturning: the INSERT ends in RETURNING id and is run with QueryRow (postgres).
	// InsertLastID: the INSERT is run with Exec and the id read from LastInsertId (mysql).
	// Both are false for uuid ids, which the service generates before inserting.
	InsertReturning bool
	InsertLastID    bool
}

// IDView describes a module's primary key.
type IDView struct {
	Type        string // int | bigint | uuid (as written in forge.yaml)
	GoType      string // int64 | string
	Auto        bool   // generated by the database (auto-increment)
	SwaggerType string // integer | string
	Zero        string // Go literal of the zero value
	Missing     string // Go literal of a well-formed id that never exists (tests)
	MissingPath string // the same id as a URL path segment (tests)
}

func buildID(idType string) IDView {
	if idType == "uuid" {
		const missing = "00000000-0000-0000-0000-000000000000"
		return IDView{Type: idType, GoType: "string", SwaggerType: "string",
			Zero: `""`, Missing: strconv.Quote(missing), MissingPath: missing}
	}
	return IDView{Type: idType, GoType: "int64", Auto: true, SwaggerType: "integer",
		Zero: "0", Missing: "999999999", MissingPath: "999999999"}
}

// ModuleView is the data passed to every module template.
type ModuleView struct {
	Module  string
	Dialect string
	Swagger bool

	Raw         string
	HumanName   string
	HumanPlural string
	Entity      string
	EntityLower string
	Plural      string
	IDParam     string
	Table       string
	Route       string
	FilePrefix  string
	Tag         string
	ID          IDView

	Fields       []FieldView
	CreateFields []FieldView
	UpdateFields []FieldView
	UniqueFields []FieldView

	HasList, HasGet, HasCreate, HasUpdate, HasDelete bool
	Custom                                           []CustomView
	SQL                                              SQLView

	NeedsIDParam    bool // some endpoint reads the {id} path parameter
	HandlerTests    bool
	HasRequired     bool
	CreateJSON      string
	UpdateJSON      string
	UpdateTestField *FieldView
}

// ptrRequired lists types whose zero value is meaningful, so a required field must still
// be a pointer in the DTO (the validator's `required` rejects 0/false/zero time otherwise).
var ptrRequired = map[string]bool{"int": true, "bigint": true, "float": true, "bool": true, "timestamp": true}

func baseGoType(f schema.Field) string {
	switch f.Type {
	case "int":
		return "int"
	case "bigint":
		return "int64"
	case "bool":
		return "bool"
	case "float":
		return "float64"
	case "timestamp":
		return "time.Time"
	default:
		return "string"
	}
}

func validateTag(f schema.Field, required bool) string {
	parts := []string{"omitempty"}
	if required {
		parts[0] = "required"
	}
	switch f.Type {
	case "string", "text":
		if f.Min != nil {
			parts = append(parts, "min="+strconv.Itoa(*f.Min))
		}
		if f.Max != nil {
			parts = append(parts, "max="+strconv.Itoa(*f.Max))
		}
		if f.Format != "" {
			parts = append(parts, f.Format)
		}
	case "int", "bigint", "float":
		if f.Min != nil {
			parts = append(parts, "gte="+strconv.Itoa(*f.Min))
		}
		if f.Max != nil {
			parts = append(parts, "lte="+strconv.Itoa(*f.Max))
		}
	case "enum":
		parts = append(parts, "oneof="+strings.Join(f.Values, " "))
	case "decimal":
		parts = append(parts, "numeric")
	case "uuid":
		parts = append(parts, "uuid")
	}
	if f.Validate != "" {
		parts = append(parts, f.Validate)
	}
	return strings.Join(parts, ",")
}

// sampleFor returns a valid JSON literal and Go literal for a field.
func sampleFor(f schema.Field) (jsonLit, goLit string) {
	switch f.Type {
	case "int":
		v := 1
		if f.Min != nil && *f.Min > v {
			v = *f.Min
		}
		s := strconv.Itoa(v)
		return s, s
	case "bigint":
		v := 1
		if f.Min != nil && *f.Min > v {
			v = *f.Min
		}
		s := strconv.Itoa(v)
		return s, "int64(" + s + ")"
	case "float":
		v := 1.5
		if f.Min != nil && float64(*f.Min) >= v {
			v = float64(*f.Min) + 0.5
		}
		s := strconv.FormatFloat(v, 'f', -1, 64)
		if !strings.Contains(s, ".") {
			s += ".0"
		}
		return s, s
	case "bool":
		return "true", "true"
	case "decimal":
		return `"10.50"`, `"10.50"`
	case "timestamp":
		return `"2026-01-01T00:00:00Z"`, "time.Date(2026, time.January, 1, 0, 0, 0, 0, time.UTC)"
	case "uuid":
		q := strconv.Quote("00000000-0000-0000-0000-000000000001")
		return q, q
	case "enum":
		q := strconv.Quote(f.Values[0])
		return q, q
	default:
		s := "sample_" + f.Name
		switch f.Format {
		case "email":
			s = "user@example.com"
		case "url":
			s = "https://example.com"
		}
		if f.Min != nil {
			for len(s) < *f.Min {
				s += "x"
			}
		}
		if f.Max != nil && len(s) > *f.Max {
			s = s[:*f.Max]
		}
		q := strconv.Quote(s)
		return q, q
	}
}

func goDefault(f schema.Field) string {
	switch f.Type {
	case "int", "bigint", "float", "bool":
		return f.Default
	default:
		return strconv.Quote(f.Default)
	}
}

func buildField(f schema.Field, m *schema.Module) FieldView {
	name := naming.Pascal(f.Name)
	base := baseGoType(f)

	v := FieldView{
		GoName:   name,
		Col:      f.Name,
		BaseType: base,
		GoType:   base,
		Nullable: f.Nullable,
		Unique:   f.Unique,
		Required: f.Required,
	}
	if f.Nullable {
		v.GoType = "*" + base
	}
	v.Doc = "the `" + f.Name + "` value"
	if f.Description != "" {
		v.Doc = f.Description
	}

	v.InCreate = containsStr(m.DTO.Create, f.Name)
	v.InUpdate = containsStr(m.DTO.Update, f.Name)

	createPtr := !f.Required || ptrRequired[f.Type]
	v.CreateType = base
	if createPtr {
		v.CreateType = "*" + base
	}
	v.UpdateType = "*" + base
	v.CreateValidate = validateTag(f, f.Required)
	v.UpdateValidate = validateTag(f, false)

	switch {
	case f.Nullable:
		v.CreateAssign = fmt.Sprintf("item.%[1]s = req.%[1]s", name)
		v.UpdateAssign = fmt.Sprintf("if req.%[1]s != nil {\n\titem.%[1]s = req.%[1]s\n}", name)
	case createPtr:
		v.CreateAssign = fmt.Sprintf("if req.%[1]s != nil {\n\titem.%[1]s = *req.%[1]s\n}", name)
		v.UpdateAssign = fmt.Sprintf("if req.%[1]s != nil {\n\titem.%[1]s = *req.%[1]s\n}", name)
	default:
		v.CreateAssign = fmt.Sprintf("item.%[1]s = req.%[1]s", name)
		v.UpdateAssign = fmt.Sprintf("if req.%[1]s != nil {\n\titem.%[1]s = *req.%[1]s\n}", name)
	}
	if f.Default != "" {
		v.DefaultInit = fmt.Sprintf("item.%s = %s", name, goDefault(f))
	}

	jsonLit, goLit := sampleFor(f)
	v.SampleJSON = jsonLit
	v.SampleCreate = goLit
	if createPtr {
		v.SampleCreate = "ptr(" + goLit + ")"
	}
	v.SampleUpdate = "ptr(" + goLit + ")"
	return v
}

func containsStr(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// buildView derives everything the templates need for module m.
func buildView(m *schema.Module, project schema.Project, d dialect.Dialect, swagger bool) *ModuleView {
	mv := &ModuleView{
		Module:      project.Module,
		Dialect:     d.Name(),
		Swagger:     swagger,
		Raw:         m.Name,
		HumanName:   naming.Human(m.Name),
		HumanPlural: naming.Human(m.Plural),
		Entity:      naming.Pascal(m.Name),
		EntityLower: naming.Camel(m.Name),
		Plural:      naming.Pascal(m.Plural),
		IDParam:     naming.Camel(m.Name) + "ID",
		Table:       m.Table,
		Route:       naming.Kebab(m.Plural),
		FilePrefix:  naming.Snake(m.Name),
		Tag:         naming.Pascal(m.Plural),
		ID:          buildID(m.ID),
		HasList:     m.HasCRUD("list"),
		HasGet:      m.HasCRUD("get"),
		HasCreate:   m.HasCRUD("create"),
		HasUpdate:   m.HasCRUD("update"),
		HasDelete:   m.HasCRUD("delete"),
	}

	customValidate := false
	for _, f := range m.Fields {
		fv := buildField(f, m)
		mv.Fields = append(mv.Fields, fv)
		if fv.InCreate {
			mv.CreateFields = append(mv.CreateFields, fv)
			if f.Required {
				mv.HasRequired = true
			}
		}
		if fv.InUpdate {
			mv.UpdateFields = append(mv.UpdateFields, fv)
		}
		if f.Validate != "" && (fv.InCreate || fv.InUpdate) {
			customValidate = true
		}
	}

	// SQL (needs the final field list, so it is built after the loop).
	mv.SQL, mv.Fields = buildSQL(m, mv, d)
	// buildSQL returns fields with FindBySQL set; rebuild the filtered views from them.
	mv.CreateFields, mv.UpdateFields, mv.UniqueFields = nil, nil, nil
	for _, fv := range mv.Fields {
		if fv.InCreate {
			mv.CreateFields = append(mv.CreateFields, fv)
		}
		if fv.InUpdate {
			mv.UpdateFields = append(mv.UpdateFields, fv)
		}
		if fv.Unique {
			mv.UniqueFields = append(mv.UniqueFields, fv)
		}
	}

	for _, c := range m.Endpoints.Custom {
		path := strings.ReplaceAll(c.Path, "{id}", "{"+mv.IDParam+"}")
		summary := c.Summary
		if summary == "" {
			summary = naming.Pascal(c.Name) + " a " + mv.HumanName
		}
		mv.Custom = append(mv.Custom, CustomView{
			Name:        c.Name,
			GoMethod:    naming.Pascal(c.Name) + mv.Entity,
			HTTPMethod:  c.Method,
			MethodLower: strings.ToLower(c.Method),
			Path:        path,
			Summary:     summary,
			Permission:  permissionFor(m, c.Name, c.Permission),
			HasID:       strings.Contains(c.Path, "{id}"),
		})
	}

	mv.NeedsIDParam = mv.HasGet || mv.HasUpdate || mv.HasDelete
	for _, c := range mv.Custom {
		mv.NeedsIDParam = mv.NeedsIDParam || c.HasID
	}

	// Test samples.
	var createJSON []string
	for _, fv := range mv.CreateFields {
		if fv.Required {
			createJSON = append(createJSON, strconv.Quote(fv.Col)+": "+fv.SampleJSON)
		}
	}
	mv.CreateJSON = "{" + strings.Join(createJSON, ", ") + "}"
	if len(mv.UpdateFields) > 0 {
		f := mv.UpdateFields[0]
		mv.UpdateTestField = &f
		mv.UpdateJSON = "{" + strconv.Quote(f.Col) + ": " + f.SampleJSON + "}"
	}
	mv.HandlerTests = mv.HasList && mv.HasGet && mv.HasCreate && mv.HasUpdate && mv.HasDelete && !customValidate
	if !mv.HasUpdate {
		mv.UpdateJSON = ""
	}
	return mv
}

func permissionFor(m *schema.Module, action, explicit string) string {
	if explicit != "" {
		return explicit
	}
	return m.Security.Permissions[action]
}
