package gen

import (
	"strings"
	"testing"

	"github.com/Imanuelkarl/forge/internal/dialect"
	"github.com/Imanuelkarl/forge/internal/schema"
)

func modules(idType string) schema.Modules {
	s := &schema.Schema{
		Project: schema.Project{Name: "app", Module: "example.com/app", Database: "postgres", IDType: idType},
		Modules: schema.Modules{{
			Name:   "user",
			Fields: schema.FieldList{{Name: "token", Type: "uuid", Required: true, Unique: true}},
		}},
	}
	s.Normalize()
	return s.Modules
}

func TestMigrationIDAndUUIDColumns(t *testing.T) {
	pg, _ := dialect.Get("postgres")
	my, _ := dialect.Get("mysql")

	cases := []struct {
		name     string
		idType   string
		d        dialect.Dialect
		contains []string
	}{
		{"postgres int", "int", pg, []string{`"id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`, `"token" uuid NOT NULL`}},
		{"postgres bigint", "bigint", pg, []string{`"id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`}},
		{"postgres uuid", "uuid", pg, []string{`"id" uuid NOT NULL PRIMARY KEY`}},
		{"mysql int", "int", my, []string{"`id` int NOT NULL AUTO_INCREMENT PRIMARY KEY", "`token` char(36) NOT NULL"}},
		{"mysql uuid", "uuid", my, []string{"`id` char(36) NOT NULL PRIMARY KEY"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			up, _ := migrationSQL(modules(c.idType), 0, c.d)
			for _, want := range c.contains {
				if !strings.Contains(up, want) {
					t.Errorf("migration lacks %q:\n%s", want, up)
				}
			}
		})
	}
}

func TestInsertOmitsAutoID(t *testing.T) {
	pg, _ := dialect.Get("postgres")
	my, _ := dialect.Get("mysql")

	mods := modules("int")
	mv := buildView(&mods[0], schema.Project{Module: "example.com/app"}, pg, false)
	if strings.Contains(mv.SQL.Insert, `(\"id\"`) || !strings.HasSuffix(mv.SQL.Insert, `RETURNING \"id\""`) {
		t.Errorf("postgres int insert should omit id and return it: %s", mv.SQL.Insert)
	}
	if !mv.SQL.InsertReturning || mv.SQL.InsertLastID {
		t.Errorf("postgres should use RETURNING")
	}

	mv = buildView(&mods[0], schema.Project{Module: "example.com/app"}, my, false)
	if strings.Contains(mv.SQL.Insert, "RETURNING") || !mv.SQL.InsertLastID {
		t.Errorf("mysql should use LastInsertId: %s", mv.SQL.Insert)
	}

	mods = modules("uuid")
	mv = buildView(&mods[0], schema.Project{Module: "example.com/app"}, pg, false)
	if !strings.Contains(mv.SQL.Insert, `(\"id\"`) || mv.SQL.InsertReturning || mv.SQL.InsertLastID {
		t.Errorf("uuid insert should include the id: %s", mv.SQL.Insert)
	}
}
