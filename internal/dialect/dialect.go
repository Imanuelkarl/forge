// Package dialect isolates everything that differs between SQL databases, so adding
// a new database means adding one type here (and one migrate driver import).
package dialect

import (
	"fmt"
	"strconv"
	"strings"
)

// Dialect describes a supported SQL database.
type Dialect interface {
	Name() string
	// Quote quotes an identifier (table or column name).
	Quote(ident string) string
	// Placeholder returns the n-th (1-based) bind parameter.
	Placeholder(n int) string
	// TimestampType is the column type used for created_at/updated_at and timestamp fields.
	TimestampType() string
	// UUIDType is the column type used for uuid fields and uuid primary keys.
	UUIDType() string
	// AutoIncrementPK is the full column definition of an auto-incrementing integer primary key.
	AutoIncrementPK(bigint bool) string
	// SupportsReturning reports whether INSERT ... RETURNING can read back a generated id
	// (otherwise the driver's LastInsertId is used).
	SupportsReturning() bool
	// InlineIndexes reports whether indexes must be declared inside CREATE TABLE.
	InlineIndexes() bool
	// DriverImport is the database/sql driver imported by the application.
	DriverImport() string
	// DriverName is the name the driver registers with database/sql.
	DriverName() string
	// MigrateImport is the golang-migrate database driver package.
	MigrateImport() string
	// DefaultURL is the DATABASE_URL written to .env.example.
	DefaultURL(dbName string) string
}

// Names lists the supported dialects.
var Names = []string{"postgres", "mysql"}

// Get returns the dialect with the given name.
func Get(name string) (Dialect, error) {
	switch name {
	case "postgres":
		return postgres{}, nil
	case "mysql":
		return mysql{}, nil
	default:
		return nil, fmt.Errorf("unsupported database %q (supported: %s)", name, strings.Join(Names, ", "))
	}
}

type postgres struct{}

func (postgres) Name() string { return "postgres" }
func (postgres) Quote(i string) string {
	return `"` + strings.ReplaceAll(i, `"`, `""`) + `"`
}
func (postgres) Placeholder(n int) string { return "$" + strconv.Itoa(n) }
func (postgres) TimestampType() string    { return "timestamptz" }
func (postgres) UUIDType() string         { return "uuid" }
func (postgres) SupportsReturning() bool  { return true }
func (postgres) InlineIndexes() bool      { return false }
func (postgres) AutoIncrementPK(bigint bool) string {
	if bigint {
		return "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}
	return "integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
}
func (postgres) DriverImport() string { return "github.com/jackc/pgx/v5/stdlib" }
func (postgres) DriverName() string   { return "pgx" }
func (postgres) MigrateImport() string {
	return "github.com/golang-migrate/migrate/v4/database/postgres"
}
func (postgres) DefaultURL(db string) string {
	return "postgres://postgres:postgres@localhost:5432/" + db + "?sslmode=disable"
}

type mysql struct{}

func (mysql) Name() string { return "mysql" }
func (mysql) Quote(i string) string {
	return "`" + strings.ReplaceAll(i, "`", "``") + "`"
}
func (mysql) Placeholder(int) string  { return "?" }
func (mysql) TimestampType() string   { return "datetime(6)" }
func (mysql) UUIDType() string        { return "char(36)" }
func (mysql) SupportsReturning() bool { return false }
func (mysql) InlineIndexes() bool     { return true }
func (mysql) AutoIncrementPK(bigint bool) string {
	if bigint {
		return "bigint NOT NULL AUTO_INCREMENT PRIMARY KEY"
	}
	return "int NOT NULL AUTO_INCREMENT PRIMARY KEY"
}
func (mysql) DriverImport() string { return "github.com/go-sql-driver/mysql" }
func (mysql) DriverName() string   { return "mysql" }
func (mysql) MigrateImport() string {
	return "github.com/golang-migrate/migrate/v4/database/mysql"
}
func (mysql) DefaultURL(db string) string {
	return "mysql://root:password@tcp(localhost:3306)/" + db + "?parseTime=true&charset=utf8mb4"
}
